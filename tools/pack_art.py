"""Pack the generated art in assets/ into src/art.js as WebP data URIs.

Stamps (map engravings) get an opaque paper silhouette under the ink so that
overlapping mountains and woods hide one another like on an engraved chart.
Emblems are reduced to alpha masks: the UI tints them with each domain's ink.
Usage: python3 tools/pack_art.py"""
import base64, io, glob, os, json
import numpy as np
from PIL import Image, ImageFilter, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, 'assets')

def uri(img, fmt='WEBP', **kw):
    b = io.BytesIO(); img.save(b, fmt, **kw)
    return f"data:image/{fmt.lower()};base64," + base64.b64encode(b.getvalue()).decode()

def silhouette(alpha):
    m = Image.fromarray(((alpha > 0.18) * 255).astype(np.uint8))
    m = m.filter(ImageFilter.MaxFilter(7)).filter(ImageFilter.MinFilter(5))
    # fill holes: flood the outside from a padded border, everything not reached is inside
    w, h = m.size; p = Image.new('L', (w + 2, h + 2), 0); p.paste(m, (1, 1))
    ImageDraw.floodfill(p, (0, 0), 128)
    inside = np.asarray(p)[1:-1, 1:-1] != 128
    s = Image.fromarray((inside * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.2))
    return np.asarray(s).astype(np.float32) / 255

def stamp(path):
    im = np.asarray(Image.open(path).convert('RGBA')).astype(np.float32) / 255
    ink = im[..., 3]; fill = silhouette(ink) * 0.94
    paper = np.array([0.87, 0.81, 0.68]); inkc = np.array([0.15, 0.12, 0.09])
    a = ink + fill * (1 - ink)
    rgb = (inkc * ink[..., None] + paper * (fill * (1 - ink))[..., None]) / np.maximum(a[..., None], 1e-4)
    out = Image.fromarray((np.dstack([rgb, a]) * 255).astype(np.uint8), 'RGBA')
    return uri(out, quality=88)

def mask(path, size):
    im = Image.open(path).convert('RGBA').resize((size, size), Image.LANCZOS)
    a = im.getchannel('A'); w = Image.new('RGBA', im.size, (255, 255, 255, 0)); w.putalpha(a)
    return uri(w, quality=90)

def plain(path, size=None, **kw):
    im = Image.open(path)
    if size: im = im.resize(size, Image.LANCZOS)
    return uri(im, **kw)

art = {
    'stamp': {os.path.basename(f)[:-4]: stamp(f) for f in sorted(glob.glob(f'{A}/stamps/*.png'))},
    'charge': {os.path.basename(f)[:-4]: plain(f, quality=90) for f in sorted(glob.glob(f'{A}/charges/*.png'))},
    'emblem': {os.path.basename(f)[:-4]: mask(f, 112) for f in sorted(glob.glob(f'{A}/emblems/*.png'))},
    'compass': plain(f'{A}/compass.png', (256, 256), quality=90),
    'card': plain(f'{A}/card.jpg', None, quality=82),
}
js = ('/* generated by tools/pack_art.py from assets/ (Higgsfield-generated art) */\n'
      'const ART=' + json.dumps(art, separators=(',', ':')) + ';\n')
open(os.path.join(ROOT, 'src', 'art.js'), 'w').write(js)
print('art.js', round(len(js) / 1024), 'KB')
